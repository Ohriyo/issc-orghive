import { readFileSync } from 'node:fs';
import request from 'supertest';
import { beforeAll, describe, expect, it } from 'vitest';
import type { SearchResponse } from '@orghive/shared';
import { memoryCache } from '#src/lib/cache';
import { pdfText } from '#src/lib/file-processing';
import { createDocumentRepository } from '#src/repositories/document.repository';
import { createAccountRepository } from '#src/repositories/account.repository';
import { createDocumentViewerService } from '#src/services/document-viewer.service';
import { createSearchService } from '#src/services/search.service';
import { createTokenService } from '#src/services/token.service';
import { testKeys } from './auth-fixtures';
import { buildWorld, createTestDocument, resetDb, testDb, type World } from './db';
import { buildTestApp } from './helpers';

const db = testDb();
const tokens = createTokenService(testKeys());

/** A sample from `pnpm --filter api db:seed`, generated by prisma/seed/generate_sample_pdfs.py. */
const SEEDED_PDF = 'prisma/seed/assets/jpice-barangay-water-survey-report.pdf';
/** Appears only in that file's text, never in a seeded title or description. */
const PDF_ONLY_PHRASE = 'hydraulic ram pump';

/** Accounts: JPICE's own, its CSC, a sibling SBO, the ISSC (admin), and none (student). */
type Person = 'student' | 'ceaGovernor' | 'jpiceOfficer' | 'psmeOfficer' | 'admin';

let world: World;
let app: ReturnType<typeof buildTestApp>;
const tokenOf = {} as Record<Person, string>;
const userIdOf = {} as Record<Person, string>;
/** A word unique to this run, so results never depend on other tests' rows. */
const WORD = `qx${crypto.randomUUID().slice(0, 8)}`;
let docs: Record<'public' | 'governing' | 'private' | 'archived' | 'scanning' | 'psme', string>;
let pdfDocId: string;

function call(path: string, token?: string) {
  const req = request(app).get(`/api/v1${path}`);
  return token ? req.set('Authorization', `Bearer ${token}`) : req;
}

async function ids(path: string, token?: string) {
  const body = (await call(path, token).expect(200)).body as SearchResponse;
  return body.items.map((hit) => hit.document.id).sort();
}

beforeAll(async () => {
  await resetDb(db);
  world = await buildWorld(db);

  const people: Record<Person, string> = {
    student: world.users.outsider.id,
    ceaGovernor: world.users.governor.id,
    jpiceOfficer: world.users.officer.id,
    psmeOfficer: world.users.psme.id,
    admin: world.users.issc.id,
  };
  for (const [key, userId] of Object.entries(people) as [Person, string][]) {
    userIdOf[key] = userId;
    tokenOf[key] = (await tokens.sign({ userId, passwordChangeRequired: false })).token;
  }

  const make = async (
    title: string,
    extra: Partial<Parameters<typeof createTestDocument>[1]> = {},
  ) =>
    (
      await createTestDocument(db, {
        organizationId: world.orgs.jpice.id,
        typeId: world.types.proposal.id,
        title: `${WORD} ${title}`,
        status: 'available',
        createdById: userIdOf.jpiceOfficer,
        ...extra,
      })
    ).id;
  docs = {
    public: await make('public proposal'),
    governing: await make('governing proposal', { visibility: 'governing' }),
    private: await make('private proposal', { visibility: 'private' }),
    archived: await make('archived proposal', { status: 'archived' }),
    scanning: await make('scanning proposal', { status: 'scanning' }),
    psme: await make('psme report', {
      organizationId: world.orgs.psme.id,
      typeId: world.types.report.id,
      academicYear: '2025-2026',
    }),
  };

  // The seeded sample, stored as the seed and the worker store any PDF: its extracted text.
  const pdf = await createTestDocument(db, {
    organizationId: world.orgs.jpice.id,
    typeId: world.types.report.id,
    title: 'Narrative Report: Barangay Potable Water Survey',
    status: 'available',
    createdById: userIdOf.jpiceOfficer,
  });
  await db.document.update({
    where: { id: pdf.id },
    data: {
      description: 'Summary of the JPICE community survey of household water sources.',
      contentText: await pdfText(readFileSync(SEEDED_PDF)),
    },
  });
  pdfDocId = pdf.id;

  const accounts = createAccountRepository(db);
  app = buildTestApp({
    tokens,
    search: createSearchService({
      documents: createDocumentRepository(db),
      viewers: createDocumentViewerService({ accounts }),
      storage: { presignGet: (key) => Promise.resolve(`https://storage.test/${key}`) },
      cache: memoryCache(),
    }),
  });
});

describe('GET /search validation', () => {
  it('400s a missing or one-character query', async () => {
    await call('/search').expect(400);
    await call('/search?q=a').expect(400);
  });

  it('400s malformed filters', async () => {
    await call('/search?q=bridge&year=2026').expect(400);
    await call('/search?q=bridge&org=Not%20a%20slug').expect(400);
    await call('/search?q=bridge&page=0').expect(400);
  });

  it('401s an invalid token instead of serving the public results', async () => {
    await call('/search?q=bridge', 'abc.def.ghi').expect(401);
  });

  it('returns no results (not 404) for an unknown organization', async () => {
    expect(await ids(`/search?q=${WORD}&org=nobody`)).toEqual([]);
  });
});

describe('GET /search visibility (the repository filter decides)', () => {
  it('shows a visitor only public files', async () => {
    expect(await ids(`/search?q=${WORD}`)).toEqual([docs.public, docs.psme].sort());
  });

  it('shows an account acting for no organization the same as a visitor', async () => {
    expect(await ids(`/search?q=${WORD}`, tokenOf.student)).toEqual(
      [docs.public, docs.psme].sort(),
    );
  });

  it('adds governing files for a governing body (the college CSC)', async () => {
    expect(await ids(`/search?q=${WORD}`, tokenOf.ceaGovernor)).toEqual(
      [docs.public, docs.governing, docs.psme].sort(),
    );
  });

  it('adds private files for the organization itself, but never archived or unscanned ones', async () => {
    expect(await ids(`/search?q=${WORD}`, tokenOf.jpiceOfficer)).toEqual(
      [docs.public, docs.governing, docs.private, docs.psme].sort(),
    );
  });

  it('shows another organization’s officer only public files', async () => {
    expect(await ids(`/search?q=${WORD}`, tokenOf.psmeOfficer)).toEqual(
      [docs.public, docs.psme].sort(),
    );
  });

  it('shows the ISSC governing files too, but never a private one', async () => {
    expect(await ids(`/search?q=${WORD}`, tokenOf.admin)).toEqual(
      [docs.public, docs.governing, docs.psme].sort(),
    );
  });
});

describe('GET /search filters', () => {
  it('narrows by organization, college, type and academic year', async () => {
    expect(await ids(`/search?q=${WORD}&org=psme`)).toEqual([docs.psme]);
    expect(await ids(`/search?q=${WORD}&college=cat`)).toEqual([]);
    expect(await ids(`/search?q=${WORD}&college=cea`)).toEqual([docs.public, docs.psme].sort());
    expect(await ids(`/search?q=${WORD}&type=activity-proposal`)).toEqual([docs.public]);
    expect(await ids(`/search?q=${WORD}&year=2025-2026`)).toEqual([docs.psme]);
  });

  it('pages ranked results', async () => {
    const first = (await call(`/search?q=${WORD}&limit=1`, tokenOf.admin).expect(200))
      .body as SearchResponse;
    expect(first.items).toHaveLength(1);
    expect(first.nextPage).toBe(2);
    const last = (await call(`/search?q=${WORD}&limit=1&page=4`, tokenOf.admin).expect(200))
      .body as SearchResponse;
    expect(last.nextPage).toBeNull();
  });
});

describe('GET /search caching headers', () => {
  it('is publicly cacheable signed out and private signed in', async () => {
    const anon = await call(`/search?q=${WORD}`).expect(200);
    expect(anon.headers['cache-control']).toBe('public, max-age=60, stale-while-revalidate=300');
    expect(anon.headers.vary).toMatch(/Authorization/i);
    expect(anon.headers.etag).toBeDefined();
    const signedIn = await call(`/search?q=${WORD}`, tokenOf.student).expect(200);
    expect(signedIn.headers['cache-control']).toBe('private, no-store');
  });
});

describe('GET /search over the text inside a seeded PDF', () => {
  it('finds a phrase that exists only inside the PDF, with a highlighted snippet', async () => {
    const pdf = await db.document.findUniqueOrThrow({ where: { id: pdfDocId } });
    expect(`${pdf.title} ${pdf.description}`.toLowerCase()).not.toContain(PDF_ONLY_PHRASE);

    const body = (await call(`/search?q=${encodeURIComponent(PDF_ONLY_PHRASE)}`).expect(200))
      .body as SearchResponse;
    expect(body.items.map((hit) => hit.document.id)).toEqual([pdfDocId]);
    const matched = body.items[0]!.snippet!.filter((part) => part.match).map((p) => p.text);
    expect(matched.map((word) => word.toLowerCase())).toEqual(
      expect.arrayContaining(['hydraulic', 'ram', 'pump']),
    );
  });

  it('answers in under 300 ms (uncached: signed in)', async () => {
    const path = `/search?q=${encodeURIComponent(PDF_ONLY_PHRASE)}`;
    await call(path, tokenOf.student).expect(200); // warm up connections and JIT
    const started = performance.now();
    await call(path, tokenOf.student).expect(200);
    expect(performance.now() - started).toBeLessThan(300);
  });
});
